export const roleAbility = (r) => (D[cur].roles[r] || ['', '', ''])[2];
export const list = (key) => D[cur][key] || D.ja[key] || [];
export function joinNames(names) {
  const sep = cur === 'en' ? ', ' : cur === 'ko' ? ', ' : '、';
  return names.join(sep);
}
