let cur = 'ja';
export function detectLang() {
  try { const s = localStorage.getItem('mj-lang'); if (s && D[s]) return s; } catch {}
  const n = (navigator.language || 'ja').toLowerCase();
  if (n.startsWith('ja')) return 'ja';
  if (n.startsWith('ko')) return 'ko';
  if (n.startsWith('zh')) return 'zh';
  return 'en';
}
export function setLang(l) {
  if (!D[l]) return;
  cur = l;
  try { localStorage.setItem('mj-lang', l); } catch {}
  document.documentElement.lang = l === 'zh' ? 'zh-CN' : l;
}
export const getLang = () => cur;
export function t(key, vars) {
  let s = D[cur][key] ?? D.ja[key] ?? key;
  if (typeof s === 'string' && vars) s = s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
  return s;
}
